package org.politisationpopulairefrancaise.server.backoffice

import java.sql.Connection
import java.sql.ResultSet
import java.time.Instant
import java.time.ZoneId
import java.time.temporal.IsoFields
import java.util.Locale
import java.util.UUID
import javax.sql.DataSource
import kotlin.time.Duration
import kotlin.time.Duration.Companion.hours

enum class ValidationSessionState(val column: String) {
    OPEN("open"),
    CLOSED("closed"),
    REVOKED("revoked"),
    EXPIRED("expired"),
    ;

    companion object {
        fun of(column: String): ValidationSessionState = entries.first { it.column == column }
    }
}

/**
 * What Décider reads of a validation session (contract, section 8): its identity, week, ceiling, counter,
 * expiry and state. Never the place nor the event, never who was validated.
 */
data class ValidationSession(
    val id: UUID,
    val accountId: UUID,
    val grantId: UUID,
    val week: String,
    val sessionPubkey: String,
    val maxValidations: Int,
    val validations: Int,
    val openedAt: Instant,
    val expiresAt: Instant,
    val state: ValidationSessionState,
    val closedAt: Instant?,
) {
    fun isUsable(now: Instant): Boolean = state == ValidationSessionState.OPEN && now.isBefore(expiresAt)
}

/**
 * The validation sessions of the validators (table team_validation_session): a validator opens one in the
 * back-office and records the public key generated by their application for it; during the session the
 * application authenticates with NIP-98 requests signed by that key ([SessionRequestVerifier]).
 */
class ValidationSessions(private val dataSource: DataSource) {

    fun open(
        connection: Connection,
        accountId: UUID,
        grantId: UUID,
        sessionPubkey: String,
        maxValidations: Int,
        duration: Duration,
        now: Instant,
    ): ValidationSession {
        require(isHexKey(sessionPubkey))
        require(maxValidations in 1..MAX_VALIDATIONS)
        require(duration.isPositive() && duration <= MAX_DURATION)
        val session = ValidationSession(
            id = UUID.randomUUID(),
            accountId = accountId,
            grantId = grantId,
            week = weekOf(now),
            sessionPubkey = sessionPubkey,
            maxValidations = maxValidations,
            validations = 0,
            openedAt = now,
            expiresAt = now.plusSeconds(duration.inWholeSeconds),
            state = ValidationSessionState.OPEN,
            closedAt = null,
        )
        connection.prepareStatement(
            """
            INSERT INTO team_validation_session (id, account_id, grant_id, week, session_pubkey, max_validations, validations, opened_at, expires_at, state)
            VALUES (?, ?, ?, ?, ?, ?, 0, ?, ?, 'open')
            """.trimIndent(),
        ).use { insert ->
            insert.setObject(1, session.id)
            insert.setObject(2, accountId)
            insert.setObject(3, grantId)
            insert.setString(4, session.week)
            insert.setString(5, sessionPubkey)
            insert.setInt(6, maxValidations)
            insert.setInstant(7, now)
            insert.setInstant(8, session.expiresAt)
            insert.executeUpdate()
        }
        return session
    }

    fun find(id: UUID): ValidationSession? = dataSource.connection.use { connection ->
        connection.prepareStatement("$SELECT WHERE id = ?").use { statement ->
            statement.setObject(1, id)
            val rows = statement.executeQuery()
            if (rows.next()) rows.toSession() else null
        }
    }

    fun sessionKeyUsed(connection: Connection, pubkey: String): Boolean =
        connection.prepareStatement("SELECT 1 FROM team_validation_session WHERE session_pubkey = ?").use { statement ->
            statement.setString(1, pubkey)
            statement.executeQuery().next()
        }

    /** The open session of [accountId], if any (open state, even past its expiry not yet closed). */
    fun openOf(accountId: UUID): ValidationSession? = dataSource.connection.use { connection ->
        connection.prepareStatement("$SELECT WHERE account_id = ? AND state = 'open'").use { statement ->
            statement.setObject(1, accountId)
            val rows = statement.executeQuery()
            if (rows.next()) rows.toSession() else null
        }
    }

    /** Every open session, oldest first (the page of the administrators). */
    fun allOpen(): List<ValidationSession> = dataSource.connection.use { connection ->
        connection.prepareStatement("$SELECT WHERE state = 'open' ORDER BY opened_at, id").use { statement ->
            val rows = statement.executeQuery()
            buildList { while (rows.next()) add(rows.toSession()) }
        }
    }

    /**
     * The session of the NIP-98 key [pubkey] when it may be used right now: open, not past its expiry,
     * its validator grant live and its account active. The designating organisation is checked by the caller.
     */
    fun usableByKey(pubkey: String, now: Instant): Pair<ValidationSession, RoleGrant>? = dataSource.connection.use { connection ->
        connection.prepareStatement(
            """
            SELECT s.id, s.account_id, s.grant_id, s.week, s.session_pubkey, s.max_validations, s.validations, s.opened_at, s.expires_at, s.state, s.closed_at,
                   g.organisation_pubkey, g.granted_at, g.ends_at, g.granted_by, g.approved_by
            FROM team_validation_session s
            JOIN team_role_grant g ON g.id = s.grant_id
            JOIN team_account a ON a.id = s.account_id
            WHERE s.session_pubkey = ? AND s.state = 'open' AND s.expires_at > ?
              AND g.status = 'active' AND g.role = 'validator' AND (g.ends_at IS NULL OR g.ends_at > ?)
              AND a.status = 'active'
            """.trimIndent(),
        ).use { statement ->
            statement.setString(1, pubkey)
            statement.setInstant(2, now)
            statement.setInstant(3, now)
            val rows = statement.executeQuery()
            if (!rows.next()) return@use null
            val session = rows.toSession()
            val grant = RoleGrant(
                id = session.grantId,
                accountId = session.accountId,
                role = TeamRole.VALIDATOR,
                scope = TeamGrants.SCOPE_ALL,
                organisationPubkey = rows.getString("organisation_pubkey"),
                grantedAt = rows.instant("granted_at")!!,
                endsAt = rows.instant("ends_at"),
                grantedBy = rows.uuid("granted_by"),
                approvedBy = rows.uuid("approved_by"),
                status = GrantStatus.ACTIVE,
                closedAt = null,
            )
            session to grant
        }
    }

    /**
     * Counts one validation in the open session [id] when its ceiling allows it; false when the session
     * is no longer usable or full. Only the counter changes.
     */
    fun recordValidation(id: UUID, now: Instant): Boolean = dataSource.connection.use { connection -> recordValidation(connection, id, now) }

    /**
     * The same inside the transaction of [connection], so that Décider counts a validation in the same
     * transaction as the validation itself (both or neither; une-personne-une-voix.md 4.3).
     */
    fun recordValidation(connection: Connection, id: UUID, now: Instant): Boolean {
        return connection.prepareStatement(
            "UPDATE team_validation_session SET validations = validations + 1 WHERE id = ? AND state = 'open' AND expires_at > ? AND validations < max_validations",
        ).use { update ->
            update.setObject(1, id)
            update.setInstant(2, now)
            update.executeUpdate() == 1
        }
    }

    /** Ends the open session [id] with [state] (closed by the validator, revoked, expired); returns it, or null when not open. */
    fun end(connection: Connection, id: UUID, state: ValidationSessionState, now: Instant): ValidationSession? {
        require(state != ValidationSessionState.OPEN)
        return connection.prepareStatement("UPDATE team_validation_session SET state = ?, closed_at = ? WHERE id = ? AND state = 'open' RETURNING $COLUMNS").use { update ->
            update.setString(1, state.column)
            update.setInstant(2, now)
            update.setObject(3, id)
            val rows = update.executeQuery()
            if (rows.next()) rows.toSession() else null
        }
    }

    /** Revokes the open sessions opened under the grant [grantId]; returns them. */
    fun revokeForGrant(connection: Connection, grantId: UUID, now: Instant): List<ValidationSession> =
        connection.prepareStatement("UPDATE team_validation_session SET state = 'revoked', closed_at = ? WHERE grant_id = ? AND state = 'open' RETURNING $COLUMNS").use { update ->
            update.setInstant(1, now)
            update.setObject(2, grantId)
            val rows = update.executeQuery()
            buildList { while (rows.next()) add(rows.toSession()) }
        }

    /** Revokes the open sessions of [accountId] (emergency cut, removal); returns how many. */
    fun revokeForAccount(connection: Connection, accountId: UUID, now: Instant): Int =
        connection.prepareStatement("UPDATE team_validation_session SET state = 'revoked', closed_at = ? WHERE account_id = ? AND state = 'open'").use { update ->
            update.setInstant(1, now)
            update.setObject(2, accountId)
            update.executeUpdate()
        }

    /** Marks the open sessions past their expiry as expired; returns how many. */
    fun expireDue(now: Instant): Int = dataSource.connection.use { connection ->
        connection.prepareStatement("UPDATE team_validation_session SET state = 'expired', closed_at = expires_at WHERE state = 'open' AND expires_at <= ?").use { update ->
            update.setInstant(1, now)
            update.executeUpdate()
        }
    }

    private fun ResultSet.toSession(): ValidationSession = ValidationSession(
        id = uuid("id")!!,
        accountId = uuid("account_id")!!,
        grantId = uuid("grant_id")!!,
        week = getString("week"),
        sessionPubkey = getString("session_pubkey"),
        maxValidations = getInt("max_validations"),
        validations = getInt("validations"),
        openedAt = instant("opened_at")!!,
        expiresAt = instant("expires_at")!!,
        state = ValidationSessionState.of(getString("state")),
        closedAt = instant("closed_at"),
    )

    companion object {
        /** Ceiling of validations per session: 40 by default and at most (contract, section 8). */
        const val MAX_VALIDATIONS: Int = 40

        val DEFAULT_DURATION: Duration = 4.hours

        /** A session lasts at most a long day of validation. */
        val MAX_DURATION: Duration = 12.hours

        private val PARIS: ZoneId = ZoneId.of("Europe/Paris")

        /** The ISO week of [instant] in Paris, for example `2026-W45`. */
        fun weekOf(instant: Instant): String {
            val date = instant.atZone(PARIS).toLocalDate()
            return String.format(Locale.ROOT, "%04d-W%02d", date.get(IsoFields.WEEK_BASED_YEAR), date.get(IsoFields.WEEK_OF_WEEK_BASED_YEAR))
        }

        private const val COLUMNS = "id, account_id, grant_id, week, session_pubkey, max_validations, validations, opened_at, expires_at, state, closed_at"
        private const val SELECT = "SELECT $COLUMNS FROM team_validation_session"
    }
}
