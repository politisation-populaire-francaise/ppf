#!/usr/bin/env python3
"""Generates the Kotlin ImageVector definitions of the Lucide icons used by the application.

The visual identity of the platform uses the Lucide icon set (ISC license, see
tools/icons/lucide/LICENSE). Only the icons the application needs are kept, as SVG sources in
tools/icons/lucide/, and turned here into pure Kotlin vector definitions so that every platform
draws exactly the same icon without any resource parser. Run from the repository root, after
adding or updating an SVG file:

    python3 -I tools/icons/generate_icons.py

Output: shared/ui/src/commonMain/kotlin/org/politisationpopulairefrancaise/ui/icons/Lucide.kt
"""

import pathlib
import re
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCES = ROOT / "tools" / "icons" / "lucide"
OUTPUT = ROOT / "shared" / "ui" / "src" / "commonMain" / "kotlin" / "org" / "politisationpopulairefrancaise" / "ui" / "icons" / "Lucide.kt"
SVG = "{http://www.w3.org/2000/svg}"


def num(value: float) -> str:
    text = ("%.3f" % float(value)).rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def element_path(element: ET.Element) -> str:
    """Every SVG shape becomes path data, the only primitive of an ImageVector."""
    tag = element.tag.replace(SVG, "")
    a = element.attrib
    if tag == "path":
        return a["d"]
    if tag == "circle":
        cx, cy, r = float(a["cx"]), float(a["cy"]), float(a["r"])
        return (f"M{num(cx - r)} {num(cy)}a{num(r)} {num(r)} 0 1 0 {num(2 * r)} 0"
                f"a{num(r)} {num(r)} 0 1 0 {num(-2 * r)} 0")
    if tag == "ellipse":
        cx, cy, rx, ry = float(a["cx"]), float(a["cy"]), float(a["rx"]), float(a["ry"])
        return (f"M{num(cx - rx)} {num(cy)}a{num(rx)} {num(ry)} 0 1 0 {num(2 * rx)} 0"
                f"a{num(rx)} {num(ry)} 0 1 0 {num(-2 * rx)} 0")
    if tag == "rect":
        x, y = float(a.get("x", 0)), float(a.get("y", 0))
        w, h = float(a["width"]), float(a["height"])
        rx = float(a.get("rx", a.get("ry", 0)))
        ry = float(a.get("ry", rx))
        if rx == 0 and ry == 0:
            return f"M{num(x)} {num(y)}h{num(w)}v{num(h)}h{num(-w)}z"
        return (f"M{num(x + rx)} {num(y)}h{num(w - 2 * rx)}a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(ry)}"
                f"v{num(h - 2 * ry)}a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(ry)}h{num(-(w - 2 * rx))}"
                f"a{num(rx)} {num(ry)} 0 0 1 {num(-rx)} {num(-ry)}v{num(-(h - 2 * ry))}"
                f"a{num(rx)} {num(ry)} 0 0 1 {num(rx)} {num(-ry)}z")
    if tag == "line":
        return f"M{num(a['x1'])} {num(a['y1'])}L{num(a['x2'])} {num(a['y2'])}"
    if tag in ("polyline", "polygon"):
        numbers = re.findall(r"-?\d*\.?\d+", a["points"])
        pairs = list(zip(numbers[0::2], numbers[1::2]))
        data = "M" + "L".join(f"{num(x)} {num(y)}" for x, y in pairs)
        return data + ("z" if tag == "polygon" else "")
    raise ValueError(f"unsupported SVG element <{tag}>")


def kotlin_name(file_stem: str) -> str:
    return "".join(part.capitalize() for part in file_stem.split("-"))


def main() -> None:
    version = (SOURCES / "VERSION").read_text(encoding="utf-8").strip()
    icons = []
    for svg in sorted(SOURCES.glob("*.svg")):
        root = ET.parse(svg).getroot()
        if root.attrib.get("viewBox", "0 0 24 24") != "0 0 24 24":
            raise ValueError(f"{svg.name}: unexpected viewBox")
        paths = [element_path(child) for child in root]
        icons.append((svg.stem, kotlin_name(svg.stem), paths))

    lines = [
        "// GENERATED by tools/icons/generate_icons.py from tools/icons/lucide/*.svg. Do not edit by hand.",
        f"// Lucide icons {version}, ISC license (tools/icons/lucide/LICENSE).",
        "package org.politisationpopulairefrancaise.ui.icons",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.graphics.SolidColor",
        "import androidx.compose.ui.graphics.StrokeCap",
        "import androidx.compose.ui.graphics.StrokeJoin",
        "import androidx.compose.ui.graphics.vector.ImageVector",
        "import androidx.compose.ui.graphics.vector.addPathNodes",
        "import androidx.compose.ui.unit.dp",
        "",
        "/**",
        " * The icon set of the visual identity: Lucide, 24 dp, 2 dp round strokes. The strokes are",
        " * drawn in black and tinted by the caller ([androidx.compose.material3.Icon] uses the current",
        " * content colour), so one definition serves every colour and both themes.",
        " */",
        "object Lucide {",
        "    private val cache = HashMap<String, ImageVector>()",
        "",
        "    private fun icon(name: String, vararg paths: String): ImageVector = cache.getOrPut(name) {",
        "        ImageVector.Builder(name = \"lucide-$name\", defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = 24f, viewportHeight = 24f)",
        "            .apply {",
        "                for (data in paths) {",
        "                    addPath(",
        "                        pathData = addPathNodes(data),",
        "                        stroke = SolidColor(Color.Black),",
        "                        strokeLineWidth = 2f,",
        "                        strokeLineCap = StrokeCap.Round,",
        "                        strokeLineJoin = StrokeJoin.Round,",
        "                    )",
        "                }",
        "            }",
        "            .build()",
        "    }",
        "",
    ]
    for stem, name, paths in icons:
        quoted = ", ".join('"' + p.replace("\\", "\\\\").replace('"', '\\"') + '"' for p in paths)
        lines.append(f"    val {name}: ImageVector get() = icon(\"{stem}\", {quoted})")
    lines.append("}")
    lines.append("")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(icons)} icons written to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
